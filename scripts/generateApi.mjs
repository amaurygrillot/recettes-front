// Regenerates src/api/schema.d.ts from the back end's OpenAPI contract.
// Set OPENAPI_PATH to read the contract from somewhere else than the sibling recettes-back checkout.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const DEFAULT_CONTRACT = '../recettes-back/src/main/resources/openapi/openapi.yaml'
const OUTPUT = 'src/api/schema.d.ts'

const contract = resolve(process.env.OPENAPI_PATH ?? DEFAULT_CONTRACT)

if (!existsSync(contract)) {
  console.error(`OpenAPI contract not found: ${contract}\nSet OPENAPI_PATH to its location.`)
  process.exit(1)
}

const HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`

const schema = astToString(await openapiTS(pathToFileURL(contract)))
mkdirSync(dirname(OUTPUT), { recursive: true })
writeFileSync(OUTPUT, HEADER + schema)
console.log(`${contract} → ${OUTPUT}`)
